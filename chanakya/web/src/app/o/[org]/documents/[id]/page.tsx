import Link from "next/link";
import { notFound } from "next/navigation";
import { ExternalLink } from "lucide-react";
import { getOrgContext } from "@/lib/data/session";
import { getDocumentDetail } from "@/lib/data/documents";
import { DOC_TYPE_LABEL, EXTRACTION, LICENSE, VERIFICATION } from "@/lib/domain/labels";
import { formatDate, formatDateTime } from "@/lib/domain/format";
import { Badge, DemoBadge } from "@/components/ui/badge";
import { EmptyState, Panel } from "@/components/ui/panel";
import { StatusBadge } from "@/components/ui/status";
import { Table, Td, Th, Tr } from "@/components/ui/table";
import { CorrectionForm } from "@/components/documents/correction-form";

export const metadata = { title: "Document" };

function Row({ k, children }: { k: string; children: React.ReactNode }) {
  return (
    <div className="grid grid-cols-[140px_1fr] gap-2 border-b border-border/60 px-3 py-1.5 last:border-b-0">
      <dt className="text-[11px] uppercase tracking-wide text-muted">{k}</dt>
      <dd className="min-w-0 break-words text-[12px]">{children}</dd>
    </div>
  );
}

export default async function DocumentPage({ params }: { params: Promise<{ org: string; id: string }> }) {
  const { org: slug, id } = await params;
  const { org } = await getOrgContext(slug);
  const detail = await getDocumentDetail(id);
  if (!detail) notFound();
  const { document: d, source, versions, entities, jurisdictionName } = detail;

  return (
    <div className="flex flex-col gap-2 p-2">
      <div className="border border-border bg-panel px-3 py-2">
        <div className="flex flex-wrap items-center gap-2">
          {d.is_demo ? <DemoBadge /> : null}
          <Badge>{DOC_TYPE_LABEL[d.doc_type] ?? d.doc_type}</Badge>
          <StatusBadge table={VERIFICATION} value={d.verification_status} />
          <StatusBadge table={EXTRACTION} value={d.extraction_status} />
        </div>
        <h1 className="mt-1.5 text-[15px] font-semibold leading-snug">{d.title}</h1>
        <p className="mt-0.5 text-[12px] text-muted">{d.issuing_body ?? "Issuing body not recorded"} · {jurisdictionName ?? (d.jurisdiction_level === "central" ? "Government of India (central)" : d.state_code)}</p>
        <a href={d.source_url} target="_blank" rel="noopener noreferrer nofollow" className="mt-2 inline-flex items-center gap-1 text-[12px] text-accent hover:underline">
          Open original source <ExternalLink className="size-3" />
        </a>
      </div>

      <div className="grid grid-cols-1 gap-2 xl:grid-cols-12">
        <div className="flex flex-col gap-2 xl:col-span-8">
          <Panel title="Summary" meta={d.summary ? "machine-generated · verify against source" : undefined}>
            {d.summary ? (
              <div className="p-3">
                <p className="whitespace-pre-line text-[13px] leading-relaxed">{d.summary}</p>
                <p className="mt-2 font-mono text-[10px] text-muted">Generated by {d.summary_model} · {formatDateTime(d.summary_generated_at)}. Not legal advice.</p>
              </div>
            ) : (
              <EmptyState title="No summary">Summaries are generated in Milestone 2 once text extraction is in place. Read the original source.</EmptyState>
            )}
          </Panel>
          <Panel title="Versions" meta={`${versions.length} snapshot${versions.length === 1 ? "" : "s"}`}>
            {versions.length === 0 ? <EmptyState title="No stored versions" /> : (
              <Table>
                <thead><tr><Th className="w-10">#</Th><Th>Retrieved</Th><Th>SHA-256</Th><Th>Extraction</Th><Th>Pages</Th><Th className="hidden lg:table-cell">Change summary</Th></tr></thead>
                <tbody>
                  {versions.map((v) => (
                    <Tr key={v.id}>
                      <Td className="font-mono">v{v.version_no}</Td>
                      <Td className="font-mono text-[11px]">{formatDateTime(v.retrieved_at)}</Td>
                      <Td className="font-mono text-[11px] text-muted" title={v.content_sha256}>{v.content_sha256.slice(0, 12)}…</Td>
                      <Td><StatusBadge table={EXTRACTION} value={v.extraction_status} /></Td>
                      <Td className="font-mono">{v.page_count ?? "—"}</Td>
                      <Td className="hidden text-muted lg:table-cell">{v.change_summary ?? (v.version_no === 1 ? "Initial version" : "—")}</Td>
                    </Tr>
                  ))}
                </tbody>
              </Table>
            )}
          </Panel>
          <Panel title="Linked entities" meta="links are shown with their verification status">
            {entities.length === 0 ? <EmptyState title="No linked entities" /> : (
              <ul className="divide-y divide-border/60">
                {entities.map((e) => (
                  <li key={`${e.entity_id}:${e.link_type}`} className="flex h-8 items-center gap-2 px-3">
                    {e.is_demo ? <DemoBadge /> : null}
                    <span className="w-20 font-mono text-[10px] uppercase text-muted">{e.link_type.replace("_", " ")}</span>
                    <span className="flex-1 truncate text-[12px]">{e.canonical_name}</span>
                    <StatusBadge table={VERIFICATION} value={e.verification_status} />
                  </li>
                ))}
              </ul>
            )}
          </Panel>
        </div>

        <div className="flex flex-col gap-2 xl:col-span-4">
          <Panel title="Provenance">
            <dl>
              <Row k="Document ID"><span className="font-mono">{d.external_id}</span></Row>
              <Row k="Published">{formatDate(d.published_on)}</Row>
              <Row k="Effective">{d.effective_on ? formatDate(d.effective_on) : <span className="text-muted">Not established</span>}</Row>
              <Row k="First retrieved">{formatDateTime(d.first_retrieved_at)}</Row>
              <Row k="Last checked">{formatDateTime(d.last_checked_at)}</Row>
              <Row k="Current version">{versions.find((v) => v.id === d.current_version_id)?.version_no ? `v${versions.find((v) => v.id === d.current_version_id)?.version_no}` : "—"}</Row>
              <Row k="Language">{d.language}</Row>
              <Row k="Source URL"><a href={d.source_url} target="_blank" rel="noopener noreferrer nofollow" className="break-all font-mono text-[11px] text-accent hover:underline">{d.source_url}</a></Row>
              <Row k="Sectors">{d.sectors.length ? d.sectors.join(", ") : <span className="text-muted">Unclassified</span>}</Row>
            </dl>
          </Panel>
          <Panel title="Source & licence">
            {source ? (
              <dl>
                <Row k="Source"><span className="inline-flex items-center gap-2">{source.is_demo ? <DemoBadge /> : null}{source.name}</span></Row>
                <Row k="Publisher">{source.publisher}</Row>
                <Row k="Licence"><StatusBadge table={LICENSE} value={source.license_status} /></Row>
                {source.license_notes ? <Row k="Notes"><span className="text-muted">{source.license_notes}</span></Row> : null}
                {d.license_note ? <Row k="Document note"><span className="text-muted">{d.license_note}</span></Row> : null}
                {source.terms_url ? <Row k="Terms"><a className="text-accent hover:underline" href={source.terms_url} target="_blank" rel="noopener noreferrer">View terms</a></Row> : null}
              </dl>
            ) : <EmptyState title="Source unavailable" />}
          </Panel>
          <Panel title="Corrections">
            <CorrectionForm orgId={org.id} orgSlug={slug} documentId={d.id} />
          </Panel>
          <Link href={`/o/${slug}/command`} className="px-1 text-[11px] text-accent hover:underline">← Command Centre</Link>
        </div>
      </div>
    </div>
  );
}
